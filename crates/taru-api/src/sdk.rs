#[must_use]
pub fn typescript_sdk() -> String {
    let document = public_openapi_v1();
    let schemas = document["components"]["schemas"]
        .as_object()
        .expect("OpenAPI schemas are an object");
    let mut schema_names = schemas.keys().cloned().collect::<Vec<_>>();
    schema_names.sort();

    let mut output = String::new();
    output.push_str("// Generated by `cargo run -p taru-api --example emit-typescript-sdk`.\n");
    output.push_str("// Do not edit generated output by hand.\n\n");
    output.push_str(&format!(
        "export const TARU_API_VERSION = \"{}\" as const;\n",
        API_VERSION
    ));
    output.push_str(&format!(
        "export const TARU_API_VERSION_HEADER = \"{}\" as const;\n\n",
        API_VERSION_HEADER
    ));
    output.push_str(&format!(
        "export const TARU_PLAYBACK_SESSION_ID_HEADER = \"{}\" as const;\n\n",
        PLAYBACK_SESSION_ID_HEADER
    ));
    output.push_str("export const TARU_PUBLIC_PATHS = [\n");
    for path in public_client_paths() {
        output.push_str(&format!("  \"{}\",\n", path));
    }
    output.push_str("] as const;\n\n");

    for name in schema_names {
        let schema = &schemas[&name];
        output.push_str(&schema_definition(&name, schema));
        output.push('\n');
    }

    output.push_str(CLIENT_RUNTIME);
    output
}

fn schema_definition(name: &str, schema: &Value) -> String {
    if schema.get("type").and_then(Value::as_str) == Some("object") {
        return interface_definition(name, schema);
    }

    format!("export type {name} = {};\n", schema_to_ts(schema))
}

fn interface_definition(name: &str, schema: &Value) -> String {
    let mut output = String::new();
    output.push_str(&format!("export interface {name} {{\n"));

    let required = schema["required"]
        .as_array()
        .map(|values| values.iter().filter_map(Value::as_str).collect::<Vec<_>>())
        .unwrap_or_default();

    let properties = schema["properties"]
        .as_object()
        .expect("object schema has properties");
    let mut property_names = properties.keys().cloned().collect::<Vec<_>>();
    property_names.sort();

    for property in property_names {
        let optional = if required.contains(&property.as_str()) {
            ""
        } else {
            "?"
        };
        output.push_str(&format!(
            "  {}{}: {};\n",
            ts_property_name(&property),
            optional,
            schema_to_ts(&properties[&property])
        ));
    }

    output.push_str("}\n");
    output
}

fn schema_to_ts(schema: &Value) -> String {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        return reference
            .rsplit('/')
            .next()
            .expect("schema ref has a name")
            .to_owned();
    }

    if let Some(all_of) = schema.get("allOf").and_then(Value::as_array) {
        let mut values = all_of.iter().map(schema_to_ts).collect::<Vec<_>>();
        if schema.get("nullable").and_then(Value::as_bool) == Some(true) {
            values.push("null".to_owned());
        }
        return values.join(" | ");
    }

    let nullable = schema.get("nullable").and_then(Value::as_bool) == Some(true);
    let mut value = if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        values
            .iter()
            .filter_map(Value::as_str)
            .map(|value| format!("\"{value}\""))
            .collect::<Vec<_>>()
            .join(" | ")
    } else {
        match schema.get("type").and_then(Value::as_str) {
            Some("array") => format!("Array<{}>", schema_to_ts(&schema["items"])),
            Some("boolean") => "boolean".to_owned(),
            Some("integer" | "number") => "number".to_owned(),
            Some("object") => "Record<string, unknown>".to_owned(),
            Some("string") => "string".to_owned(),
            _ => "unknown".to_owned(),
        }
    };

    if value.is_empty() {
        value = "string".to_owned();
    }
    if nullable {
        value.push_str(" | null");
    }

    value
}

fn ts_property_name(name: &str) -> String {
    if name
        .chars()
        .all(|ch| ch == '_' || ch.is_ascii_alphanumeric())
        && name
            .chars()
            .next()
            .is_some_and(|ch| ch == '_' || ch.is_ascii_alphabetic())
    {
        name.to_owned()
    } else {
        format!("{name:?}")
    }
}

