#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn typescript_sdk_includes_public_route_methods_and_paths() {
        let sdk = typescript_sdk();

        for path in public_client_paths() {
            assert!(sdk.contains(path), "SDK missing public path {path}");
        }

        for method in [
            "health(",
            "listLibraries(",
            "getLibrary(",
            "searchItems(",
            "getPlaybackDecision(",
            "streamSource(",
            "headStreamSource(",
            "remuxStreamSource(",
            "headRemuxStreamSource(",
            "hlsPlaylist(",
            "getPlaybackSession(",
            "cancelPlaybackSession(",
            "getUserPlaybackState(",
            "listContinueWatching(",
            "updateUserPlaybackProgress(",
            "setUserWatchedState(",
        ] {
            assert!(sdk.contains(method), "SDK missing method {method}");
        }
    }

    #[test]
    fn typescript_sdk_includes_auth_version_error_and_pagination_runtime() {
        let sdk = typescript_sdk();

        for expected in [
            "Authorization",
            "Bearer ${this.bearerToken}",
            "TARU_API_VERSION_HEADER",
            "TARU_PLAYBACK_SESSION_ID_HEADER",
            "TaruApiError",
            "ErrorResponse",
            "limit?: number",
            "offset?: number",
            "response.headers.get",
            "Content-Type",
            "JSON.stringify",
        ] {
            assert!(
                sdk.contains(expected),
                "SDK missing runtime detail {expected}"
            );
        }
    }

    #[test]
    fn typescript_sdk_excludes_admin_internal_and_secret_surfaces() {
        let sdk = typescript_sdk().to_ascii_lowercase();

        for forbidden in [
            "/admin",
            "/admin/v1",
            "/addons",
            "/addon",
            "/addon/v1",
            "/webhooks",
            "/automation",
            "/storage/backends",
            "/jobs",
            "secret_env",
            "output_path",
            "providerrawresponse",
            "taru_core",
            "taru-server",
        ] {
            assert!(
                !sdk.contains(forbidden),
                "SDK leaked forbidden term: {forbidden}"
            );
        }
    }

    #[test]
    fn typescript_package_entry_matches_generator_output() {
        let generated = typescript_sdk().replace("\r\n", "\n");
        let package_entry =
            include_str!("../../../sdk/typescript/src/index.ts").replace("\r\n", "\n");

        assert_eq!(
            package_entry, generated,
            "run `npm run generate --prefix sdk/typescript` to refresh the TypeScript SDK package entry"
        );
    }
}
